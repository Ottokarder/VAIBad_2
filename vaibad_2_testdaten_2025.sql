-- Testdaten fuer vaibad_2 (Sponsorenschwimmen 2025)
-- Automatisch erzeugt aus daten/vormittag.xlsx + daten/nachmittag.xlsx
--
-- Zwei-Phasen-Verarbeitung:
--   1) Vormittags-Datei: leert die Tabellen und schreibt Schwimmer,
--      Vormittags-Bahnen, Sponsoren und Teams.
--   2) Nachmittags-Datei: ergaenzt Nachmittags-Bahnen, legt reine
--      Nachmittags-Schwimmer neu an und fuegt zusaetzliche Sponsor-Paare
--      hinzu (Union, keine Doppelungen).
--
-- Regeln:
--   * Bahnen aus der Vormittags-Liste -> schwimmleistung_vormittag.
--   * Bahnen aus der Nachmittags-Liste -> schwimmleistung_nachmittag.
--   * Summe 'a+a' in Bahnen-Spalte: a vormittags + a nachmittags.
--   * Sponsoren werden PRO Schwimmer-Sponsor-Paar angelegt:
--     gleicher Name, aber eigener betrag_pro_bahn und limit pro Paar.
--     Unterschieden wird ueber die id. Eine manuelle Zusammenfuehrung
--     gleichnamiger Sponsoren ist spaeter moeglich.
--   * Keine Hauptsponsoren.
--   * Geburtsjahr aus dem Geburtstag-Datum abgeleitet.
--
-- Ausfuehren mit:
--   mysql -u root vaibad_2 < vaibad_2_testdaten_2025.sql
-- Setzt eine bereits angelegte Datenbank vaibad_2 voraus
-- (siehe vaibad_2_database_setup.sql).

